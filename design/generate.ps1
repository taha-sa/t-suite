param()
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
& "$root/audit-contrast.ps1" 6>$null
$t = Get-Content "$root/tokens.json" -Raw -Encoding UTF8 | ConvertFrom-Json
$utf8 = New-Object Text.UTF8Encoding $false
function Write-OutputFile($path, $lines) {
    $file = Join-Path $root "out/$path"
    [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($file)) | Out-Null
    [IO.File]::WriteAllText($file, (($lines -join "`n") + "`n"), $utf8)
}
function Flatten($obj, $prefix) {
    foreach ($p in $obj.PSObject.Properties) {
        $key = if ($prefix) { "$prefix.$($p.Name)" } else { $p.Name }
        if ($p.Value -is [pscustomobject]) { Flatten $p.Value $key }
        else { [pscustomobject]@{ Key=$key; Value=$p.Value } }
    }
}
function Id($key) { ($key.Split('.') | ForEach-Object { $_.Substring(0,1).ToUpperInvariant()+$_.Substring(1) }) -join '' }
function Argb($value) {
    if ($value -match '^#[0-9A-Fa-f]{6}$') { return 'FF'+$value.Substring(1) }
    if ($value -match '^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$') {
        return ('{0:X2}{1:X2}{2:X2}{3:X2}' -f [int][math]::Round(255*[double]::Parse($Matches[4],[cultureinfo]::InvariantCulture)),[int]$Matches[1],[int]$Matches[2],[int]$Matches[3])
    }
    return $null
}
$flat = @(Flatten $t '')
$cs = @('// Generated by design/generate.ps1. Do not edit.','using System;','using System.Drawing;','namespace TSuite.Design {','public static class TSuiteTokens {')
$kt = @('// Generated. Do not edit.','package tsuite.design','import androidx.compose.ui.graphics.Color','import androidx.compose.ui.unit.dp','import androidx.compose.ui.unit.sp','object TSuiteTokens {')
$css = @('/* Generated. Do not edit. */',':root {')
foreach ($p in $flat) {
    $id = Id $p.Key; $v = $p.Value; $argb = Argb "$v"
    $cssValue = "$v"
    if ($v -is [ValueType] -and $p.Key -notmatch 'fontWeight') { $cssValue += 'px' }
    $css += "  --$($p.Key.Replace('.','-')): $cssValue;"
    if ($argb) {
        $cs += "  public static readonly Color $id = Color.FromArgb(unchecked((int)0x$argb));"
        $kt += "  val $id = Color(0x${argb}L)"
    } elseif ($v -is [ValueType]) {
        $cs += "  public const int $id = $v;"
        $unit = if ($p.Key -match '^typography.scale' -and $p.Key -notmatch 'fontWeight') { '.sp' } elseif ($p.Key -match '^(space|radius|elevation)\.') { '.dp' } else { '' }
        $kt += "  val $id = $v$unit"
    } elseif ($v -match '^(\d+)ms$') {
        $cs += "  public static readonly TimeSpan $id = TimeSpan.FromMilliseconds($($Matches[1]));"
        $kt += "  const val $id = $($Matches[1])"
    } else {
        $quoted = ConvertTo-Json -InputObject "$v" -Compress
        $cs += "  public const string $id = $quoted;"
        $kt += "  const val $id = $quoted"
    }
}
$cs += '}}'; $kt += '}'; $css += '}'
foreach ($theme in @('dark','light')) {
    $selector = if ($theme -eq 'dark') { ':root, [data-theme="dark"]' } else { '[data-theme="light"]' }
    $css += "$selector {"
    $aliases = [ordered]@{bg='bg';s1='surface1';s2='surface2';s3='surface3';border='border';'border-hi'='borderStrong';text='text';muted='textMuted';faint='textFaint'}
    foreach ($a in $aliases.Keys) { $css += "  --${a}: var(--color-neutral-$theme-$($aliases[$a]));" }
    $css += "  --gold: var(--color-accent-tBridge-$theme-base);", "  --gold-hi: var(--color-accent-tBridge-$theme-hover);", "  --gold-lo: var(--color-accent-tBridge-$theme-pressed);", "  --gold-grad: linear-gradient(135deg, var(--gold-hi), var(--gold-lo));", "  --on-accent: var(--color-accent-tBridge-$theme-onAccent);", '}'
    $x = @('<!-- Generated. T-DeskTree accent aliases; all apps also have qualified keys. -->','<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
    $entries = [ordered]@{}
    foreach ($p in $flat) { if ((Argb "$($p.Value)") -and ($p.Key -match "\.$theme\.")) { $entries[$p.Key] = $p.Value } }
    foreach ($p in $t.color.neutral.$theme.PSObject.Properties) {
        $key = switch ($p.Name) { bg {'Bg.Base'} surface1 {'Bg.Surface1'} surface2 {'Bg.Surface2'} surface3 {'Bg.Surface3'} default { Id $p.Name } }
        $entries[$key] = $p.Value
    }
    foreach ($p in $t.color.accent.tDeskTree.$theme.PSObject.Properties) { $key = if ($p.Name -eq 'base') { 'Accent' } else { 'Accent.'+(Id $p.Name) }; $entries[$key] = $p.Value }
    foreach ($key in $entries.Keys) {
        $v = Argb $entries[$key]
        $x += "  <Color x:Key=`"Color.$key`">#$v</Color>", "  <SolidColorBrush x:Key=`"Brush.$key`" Color=`"{StaticResource Color.$key}`" />"
        if ($key -like 'Bg.*') { $x += "  <SolidColorBrush x:Key=`"$key`" Color=`"{StaticResource Color.$key}`" />" }
    }
    $x += '</ResourceDictionary>'
    Write-OutputFile "wpf/Tokens.$(Id $theme).xaml" $x
}
Write-OutputFile 'csharp/TSuiteTokens.cs' $cs
Write-OutputFile 'kotlin/TSuiteTokens.kt' $kt
